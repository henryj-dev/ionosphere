/**
 * 프로토콜 공통 크기 한도 — 여러 리스너가 **함께 바뀌어야 하는** 값이라 한 곳에서 소유한다.
 * 이전엔 `25 * 1024 * 1024`가 app.ts 4곳 + proto-lmtp + proto-imap에 흩어져 있어,
 * 한도를 올리면 "SMTP는 받는데 IMAP APPEND가 끊긴다" 같은 프로토콜별 불일치가 생겼다.
 */

/** 메시지 최대 크기(수신·제출 공통 기본값). SMTP SIZE 광고와 IMAP literal 상한의 기준. */
export const MAX_MESSAGE_BYTES = 25 * 1024 * 1024;

/**
 * POP3 유휴 연결 타임아웃 — RFC 1939 §8이 요구하는 최소 10분.
 *
 * 여기로 올린 이유: maildrop 락의 TTL이 **이 값에서 파생된다**(TTL이 유휴 타임아웃보다 짧으면
 * 살아 있는 세션의 락을 다른 MRA가 뺏는다). 두 값이 서로 다른 패키지에 흩어져 있으면
 * 한쪽만 늘렸을 때 조용히 배타성이 깨지므로, 함께 바뀌어야 하는 값으로 묶어 둔다.
 */
export const POP3_IDLE_TIMEOUT_MS = 10 * 60 * 1000;

/**
 * 수신 1통이 만들 수 있는 **외부 relay 사본** 최대 수 — forward_to와 Sieve redirect 공통.
 *
 * 근거: RFC 5228 §2.10.3("구현은 redirect 수를 제한해야 하고, 초과 시 오류를 생성해야 한다").
 * 대상이 N개면 홉마다 N배로 늘어나므로, 홉 상한(forwardMaxHops)만으로는 N^hops 증폭을 못 막는다.
 * **분기 수**도 함께 묶어야 한다.
 *
 * 여기로 올린 이유: 배달 경로(apps/server backend.ts)가 초과 시 fail closed로 아무것도
 * 릴레이하지 않는데, **생성 경로(REST·CLI)가 같은 값을 몰라 통과시켰다.** 그러면 설정은
 * 받아들여졌는데 그 주소로 온 메일이 영구 451 루프에 빠진다(재현 확인). 값이 두 곳에서
 * 필요해졌으므로 소유자를 하나로 둔다.
 */
export const MAX_RELAY_TARGETS = 4;

/**
 * 알리아스 하나가 가리킬 수 있는 **로컬 계정** 최대 수(팬아웃, 마이그레이션 006).
 *
 * 수신 1통이 계정 수만큼 append로 증폭된다(각자 쿼터·검색 색인·웹훅까지). 상한이 없으면
 * 알리아스 하나로 테넌트 전체 계정에 동시 쓰기를 걸 수 있다. 외부 릴레이(MAX_RELAY_TARGETS)와
 * 취지는 같지만 로컬 증폭이라 값이 더 크다.
 *
 * ⚠ 두 상한은 **곱해진다** — 계정마다 자기 Sieve 스크립트로 redirect할 수 있으므로
 * 통당 최대 `MAX_ALIAS_TARGETS × MAX_RELAY_TARGETS`(=128) relay가 가능하다. 어느 쪽이든
 * 올릴 때는 그 곱과 relay 총량 상한(relayPerHour)을 함께 봐야 한다.
 */
export const MAX_ALIAS_TARGETS = 32;

/**
 * 리스너 하나가 동시에 붙들 최대 연결 수.
 *
 * 없으면 소켓·파일디스크립터가 고갈될 때까지 받아들이고, 그 지점에서 **정상 사용자까지
 * 접속하지 못한다**(그리고 프로세스 전체가 같은 fd 풀을 쓰므로 다른 프로토콜도 함께 죽는다).
 * 초과분을 즉시 끊으면 최소한 이미 붙은 세션은 살아남는다.
 *
 * 값의 근거: 프로토콜별 유휴 타임아웃이 길어(IMAP 30분·POP3 10분) 정상 사용자도 연결을
 * 오래 붙들고 있다. 1024는 소규모 배포의 동시 사용자 수보다 충분히 크고, fd 기본 상한
 * (보통 1024~65536)을 프로토콜 하나가 혼자 소진하지 않을 만큼은 작다.
 */
export const MAX_LISTENER_CONNECTIONS = 1024;

/**
 * LMTP 유휴 연결 타임아웃 — 커맨드 대기 중 아무것도 오지 않으면 끊는다.
 *
 * 여기로 올린 이유: 라인 지향 6개 프로토콜 중 **LMTP만 유휴 타임아웃이 없었다**(2026-07-30 감사).
 * 다른 5개는 각자 자기 `server.ts`에 상수를 들고 있어서, 새 프로토콜을 붙일 때 "타임아웃을
 * 건다"는 규율이 전파되지 않았다 — `MAX_COMMAND_LINE`이 POP3로 전파되지 않았던 것과 같은 구조다.
 * LMTP는 **AUTH도 TLS도 없는** 표면이라 빠졌을 때의 대가가 가장 크다. `IONOSPHERE_LMTP_PORT`를
 * 켜는 순간 무인증 slowloris가 성립하고, 전 프로토콜이 단일 프로세스라 25·587·993이 함께 죽는다.
 *
 * SMTP와 같은 5분인 이유: LMTP는 RFC 2033상 SMTP의 프로파일이고 명령 왕복도 동일하다
 * (RFC 5321 §4.5.3.2가 서버 커맨드 대기에 요구하는 최소가 5분). 상대는 신뢰된 로컬 MDA뿐이라
 * 더 짧게 잡아도 되지만, 배달 백엔드가 느릴 때 정상 세션을 끊는 쪽이 더 나쁘다.
 */
export const LMTP_IDLE_TIMEOUT_MS = 5 * 60 * 1000;

/**
 * HTTP 표면이 **요청 헤더 전체**를 받기까지 허용하는 시간.
 *
 * 이것이 slowloris를 실제로 죽이는 상한이다. 공격은 헤더를 한 바이트씩 흘려보내 연결만 붙들고,
 * 연결 수 상한(MAX_LISTENER_CONNECTIONS)에 닿으면 정상 사용자가 접속하지 못한다. 그리고 이
 * 저장소는 **전 프로토콜이 단일 프로세스**라 fd가 마르면 25·587·993까지 함께 죽는다.
 * 특히 443 HTTPS 프론트는 MTA-STS 정책 배포 때문에 방화벽으로 막을 수 없는 공개 표면이다.
 *
 * 30초인 이유: 우리 HTTP 표면의 요청 헤더는 전부 작다(JMAP Basic 인증 · autoconfig GET ·
 * `/metrics` 스크레이프). 정상 클라이언트는 한 세그먼트에 헤더를 다 보내므로 30초는 느린
 * 모바일 회선까지 감안해도 넉넉하고, node 기본값(60초)보다는 짧아 실질적인 상한이 된다.
 */
export const HTTP_HEADERS_TIMEOUT_MS = 30 * 1000;

/**
 * HTTP 표면이 **요청 전체**(헤더 + 본문)를 받기까지 허용하는 시간.
 *
 * 헤더 상한과 별개인 이유: 헤더를 정상 속도로 보낸 뒤 **본문**을 한 바이트씩 흘리면
 * `HTTP_HEADERS_TIMEOUT_MS`는 이미 해제된 뒤라 아무것도 막지 못한다. 크기 상한(JMAP
 * `maxSizeUpload`)도 이 창을 못 막는다 — 총량이 작아도 무한히 느리게 보낼 수 있다.
 *
 * 5분인 이유: 이 값에 걸리는 정상 요청은 JMAP 블롭 업로드(최대 50MB)뿐이고, 5분이면 대략
 * 1.4Mbps 이상이면 통과한다. 더 짧게 잡으면 느린 회선의 첨부 업로드가 끊긴다.
 * 응답 스트리밍(JMAP EventSource)에는 적용되지 않는다 — 이 타이머는 **요청 수신**만 잰다.
 */
export const HTTP_REQUEST_TIMEOUT_MS = 5 * 60 * 1000;

/**
 * `Received:` 홉 상한 — 초과하면 메일 루프로 보고 끊는다(RFC 5321 §6.3).
 *
 * 왜 별도 상한인가: 기존 `forwardMaxHops`(X-Ionosphere-Forwarded)는 **우리 자신의 포워딩만** 센다.
 * 우리를 경유해 도는 제3자 루프는 그 헤더를 만들지 않으므로 보이지 않는다. 표준 루프 차단은
 * "모든 MTA가 남기는 Received를 센다"는 쪽이고, 그게 이 값이다.
 *
 * 30인 이유: 정상 메일이 거치는 홉은 보통 한 자릿수다(메일링리스트·포워딩을 겹쳐도 10 내외).
 * 너무 낮게 잡으면 다단 포워딩을 쓰는 정상 사용자가 끊기고, 너무 높으면 루프가 도는 동안
 * 큐와 상대 서버를 계속 때린다. Postfix 기본(50)보다는 낮게, 실사용보다는 충분히 높게 둔다.
 */
export const MAX_RECEIVED_HOPS = 30;

/**
 * 라인 지향 프로토콜(SMTP·LMTP·POP3)의 **명령 라인 상한**.
 *
 * 여기로 올린 이유: 값이 프로토콜마다 흩어져 있었고(SMTP 4096 · LMTP 4096 · **POP3는 아예 없음**),
 * 그 결과 POP3 엔진의 `feed()`가 개행 없는 바이트를 무한히 누적했다. 미인증(AUTHORIZATION)
 * 상태에서 TCP 연결 1개로 성립하고, 계속 전송하므로 유휴 타임아웃도 발동하지 않는다
 * (300MB 투입 시 RSS 90MB → 1836MB, 2026-07-30 실측). 전 프로토콜이 단일 프로세스라
 * 메일 서비스 전체가 멈춘다. 같은 결함의 SMTP판은 이미 실사고로 고쳤는데
 * (proto-smtp `MAX_DATA_LINE` 주석) 그 교훈이 POP3로 전파되지 않았다 —
 * **소유자가 없는 값은 전파되지 않는다.**
 *
 * 값의 근거: RFC 5321 §4.5.3.1.4의 명령 라인 상한은 512옥텟, RFC 1939의 POP3 명령은 그보다도
 * 짧다. 4096으로 넉넉히 잡는 건 AUTH의 SASL 데이터 라인(base64 OAuth 토큰)이 같은 라인
 * 경로를 타기 때문이다.
 */
export const MAX_COMMAND_LINE = 4096;

/**
 * IMAP 논리 라인의 텍스트 부분 상한(리터럴 제외) — ManageSieve도 같은 리더를 쓴다.
 *
 * 라인 지향 프로토콜(MAX_COMMAND_LINE)과 값이 다른 이유: IMAP은 SEARCH·FETCH·UID 시퀀스셋을
 * 한 줄에 실어 보내고(`UID FETCH 1:*` 대신 수천 개의 UID를 나열하는 클라이언트가 실제로 있다)
 * 리터럴로 쪼갤 수 없는 문법이라 4096으로는 정상 클라이언트가 끊긴다.
 */
export const MAX_IMAP_LINE_BYTES = 64 * 1024;

/**
 * 백엔드 응답을 기다리는 동안(awaiting/pending) 쌓아 둘 수 있는 파이프라인 바이트 상한.
 *
 * 왜 라인 상한과 별개인가: 대기 중에는 파서 루프가 아예 돌지 않아 **완결된 라인이 몇 개든
 * 그대로 쌓인다**. 라인 상한만으로는 이 구간이 비어 있다. 미인증 공격자도 이 창을 연다 —
 * `PASS`(POP3)나 `AUTH`(SMTP)를 보내면 백엔드가 scrypt를 도는 동안 대기 상태가 되고,
 * 그 사이 들어오는 바이트에는 어떤 상한도 적용되지 않았다.
 *
 * 정상 클라이언트는 이 구간에서 명령 몇 줄만 미리 보내므로(PIPELINING) 1MB면 충분히 넉넉하다.
 */
export const MAX_PIPELINE_PENDING_BYTES = 1024 * 1024;

/**
 * **인증 전** IMAP 리터럴 한 개의 상한.
 *
 * 왜 인증 후(MAX_MESSAGE_BYTES=25MB)와 달라야 하는가: 25MB 리터럴이 필요한 명령은 APPEND뿐이고
 * APPEND는 인증을 요구한다. 그런데 리더는 인증 상태를 보지 않아, 어차피 거절할 `LOGIN` 한 줄을
 * 위해 미인증 연결마다 25MB를 버퍼링했다. IMAP 유휴 타임아웃이 30분이라
 * MAX_LISTENER_CONNECTIONS(1024)를 곱하면 이론상 25GB다.
 *
 * 8KB인 이유: 인증 전에 리터럴을 쓰는 정상 경로는 `LOGIN {n}` 사용자명/비밀번호와
 * AUTHENTICATE의 SASL 데이터뿐이다. OAuth 토큰까지 감안해도 8KB를 넘지 않는다.
 */
export const MAX_PREAUTH_LITERAL_BYTES = 8 * 1024;

/**
 * 백엔드 대기 중 버퍼링하는 **완성된 논리 라인**의 총 바이트 상한(IMAP).
 *
 * MAX_PIPELINE_PENDING_BYTES가 "아직 파싱 안 된 바이트"를 막는 것과 달리, IMAP은 리더가 라인을
 * 완성해 큐(`queued`)에 넣고 엔진이 나중에 처리한다. 그 큐에 상한이 없으면 리터럴 상한을 지켜도
 * **작은 리터럴을 여러 개** 보내 같은 메모리를 먹을 수 있다. 상한을 넘으면 스트림 동기가 이미
 * 깨진 것으로 보고 BYE 후 끊는다(fail closed).
 */
export const MAX_QUEUED_LINE_BYTES = 1024 * 1024;

/**
 * 한 메시지의 MIME 파트(트리 노드) **총 개수** 상한.
 *
 * 왜 필요한가: 파트 하나하나가 헤더 파싱·바운더리 탐색을 한 번씩 유발하므로, 파트 수는
 * 그대로 파서의 작업량이다. 상한이 없으면 `--B` 다섯 바이트짜리 빈 파트를 늘어놓는 것만으로
 * 메시지 크기에 비해 파트 수를 최대로 부풀릴 수 있다(1바이트당 0.2파트).
 *
 * 왜 깊이 상한(`MAX_MIME_DEPTH`)만으로는 부족한가: 깊이는 **세로**만 막는다. 깊이 1짜리
 * multipart 하나에 형제 파트를 80만 개 넣으면 깊이 상한에는 걸리지 않는다. 두 축을 **같은
 * 예산 하나**로 세야 어느 쪽으로 늘려도 같은 상한에 걸린다.
 *
 * 1024인 이유: 실사용 메시지의 파트는 첨부를 넉넉히 잡아도 수십 개다(inline 이미지가 많은
 * 뉴스레터·다단 전달 메일까지 봐도 100을 넘기기 어렵다). 1024는 정상 메일보다 한 자릿수
 * 이상 크고, 파트당 비용을 곱해도 무시할 수 있을 만큼 작다.
 *
 * 초과 시 **조용히 잘라내지 않는다** — 잘라낸 트리는 "파트가 그것뿐인 정상 메시지"와 구별되지
 * 않아, 검사기(첨부 판정·본문 추출)와 파서가 같은 입력을 다르게 읽게 된다(감사 M-13과 같은 계열).
 * `parseStructure`는 초과를 감지하면 이 패키지의 기존 실패 표현대로 **단일 파트로 축소**한다.
 */
export const MAX_MIME_PARTS = 1024;

/**
 * MIME 중첩 깊이 상한 — multipart 안의 multipart, message/rfc822 안의 메시지.
 *
 * 여기로 올린 이유: 값이 파서마다 흩어져 있었고 **서로 달랐다**(`structure.ts` 20 ·
 * `body.ts` 15, 2026-07-31 감사). 그래서 16~20단계에 묻힌 첨부를 IMAP BODYSTRUCTURE는
 * 보고 본문 추출기(`hasAttachment` 판정)는 못 보는 구간이 존재했다. 같은 메시지를 두 파서가
 * 다르게 읽는 것이 이 저장소가 반복해서 당한 사고 유형이라(`MAX_COMMAND_LINE`이 POP3로
 * 전파되지 않았던 것과 같은 구조) 소유자를 하나로 둔다.
 *
 * 20인 이유: RFC는 중첩 한도를 정하지 않지만 실사용은 3~4단계면 충분하다
 * (multipart/mixed → multipart/related → multipart/alternative → text). 전달이 겹친
 * message/rfc822 체인까지 감안해 여유를 두되, 재귀 프레임이 스택을 위협하지 않을 만큼 작게 잡는다.
 */
export const MAX_MIME_DEPTH = 20;

/**
 * 한 SMTP/LMTP **세션**이 낼 수 있는 RCPT 명령 수(트랜잭션 합산).
 *
 * 왜 트랜잭션이 아니라 세션 단위인가: 상한을 트랜잭션마다 리셋하면 `RSET`(또는 새 MAIL FROM)
 * 한 줄로 한도가 초기화돼 사실상 무제한이 된다. 수신자 검증은 공격자에게 **오라클**이다 —
 * 특히 SRS 주소는 DB 조회 없이 HMAC 1회라 비용이 거의 0인데, 맞으면 250 틀리면 550으로
 * 답이 그대로 새어 나간다. 세는 단위가 세션이어야 그 처리량이 실제로 묶인다.
 *
 * 초과 응답이 **452(일시)** 인 이유: 세션 단위로 세면 정상 대량 발신자도 언젠가 닿을 수 있는데,
 * 5xx면 그 메일이 영구 실패로 버려진다. 452면 상대 MTA가 새 세션으로 재시도해 정상 배달된다 —
 * **세션 상한을 안전하게 만드는 것이 바로 이 일시성**이다.
 *
 * 1000인 이유: RFC 5321 §4.5.3.1.8은 최소 100을 요구하고, Postfix의 `smtpd_recipient_limit`
 * 기본값이 1000이다. 정상 메일링리스트 홉보다 충분히 크고, 오라클 처리량으로는 무의미할 만큼 작다.
 */
export const MAX_RCPT_PER_SESSION = 1000;

/**
 * 한 세션에서 누적 허용하는 **4xx/5xx 응답** 수 — 초과하면 421로 끊는다.
 *
 * 이것이 무차별 대입 오라클을 실제로 죽이는 상한이다. 틀린 추측은 전부 550이므로, 세션당
 * 오류를 20으로 묶으면 연결 하나가 주는 정보량이 20회로 고정된다. 공격자는 매번 새 TCP 연결을
 * 맺어야 하고, 그 지점부터는 MAX_LISTENER_CONNECTIONS와 auth-throttle이 받는다.
 *
 * 리셋하지 않는 이유는 MAX_RCPT_PER_SESSION과 같다 — `RSET`으로 지워지면 상한이 아니다.
 * 값의 근거: Postfix `smtpd_hard_error_limit` 기본값이 20이다. 정상 발신자가 한 세션에서
 * 4xx/5xx를 20번 받는 일은 없다(있다면 그 세션은 이미 실패한 세션이다).
 */
export const MAX_SMTP_ERRORS_PER_SESSION = 20;

/**
 * JMAP 업로드 한 건의 최대 바이트(`urn:ietf:params:jmap:core`의 `maxSizeUpload`).
 *
 * ★왜 여기로 올렸나(감사 5차 §9-5 조사 중 발견): 같은 `50_000_000`이 **두 곳에 하드코딩**돼
 * 있었다 — 세션 객체가 클라이언트에게 **광고하는** 값(`proto-jmap/session.ts`)과 서버가 실제로
 * **강제하는** 값(`apps/server/jmap-server.ts`). 한쪽만 바꾸면 광고와 실제가 갈라져,
 * 클라이언트는 통과할 거라 믿고 올린 업로드가 400으로 끊긴다(또는 반대로 광고보다 큰 것이
 * 통과한다). "같은 상수가 두 곳에 복제되면 소유자를 정해 올린다"는 CLAUDE.md 응집도 규약이
 * 정확히 이 자리를 가리킨다.
 *
 * `MAX_MESSAGE_BYTES`(25MB)보다 큰 이유: 업로드는 **조립 전 개별 블롭**이라 메시지 한 통과
 * 단위가 다르다. 다만 이 값이 메시지 상한보다 크다는 사실 자체는 의도된 것이며, 업로드한
 * 블롭이 그대로 25MB를 넘는 메시지가 되지는 못한다(수신·제출 경로가 각자 상한을 건다).
 */
export const MAX_JMAP_UPLOAD_BYTES = 50_000_000;
